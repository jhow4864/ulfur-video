#!/usr/bin/env python3
"""Ulfur Video 1.8.0 - ports Anime4K v4 mpv user shaders (CNN M) to GLSL ES 3.00 programs.

Input:  tools/anime4k-port/mpv/Anime4K_Restore_CNN_M.glsl, Anime4K_Upscale_CNN_x2_M.glsl
        (bloc97/Anime4K, MIT licence, see ANIME4K_LICENSE.txt - copied unmodified).
Output: app/src/main/assets/shaders/ulfur_a4k_restore_cnn_m.glsl
        app/src/main/assets/shaders/ulfur_a4k_upscale_cnn_x2_m.glsl

Each mpv "//!HOOK" pass becomes one '#if PASS == n' block; the app compiles each file once per pass
with '#version 300 es' + '#define PASS n' prepended (Anime4kPipeline.java).

Translation rules (mpv hook semantics -> GLES 3.0):
  * every pass except Depth-to-Space runs at the source resolution, so NAME_texOff(vec2(x, y)) is an
    exact texel fetch: texelFetch(NAME, clamp(P + (x, -y))) - mpv's textures are top-down, Media3's
    are bottom-up (GL convention), so the y offsets are mirrored; clamping == mpv's CLAMP_TO_EDGE.
  * NAME_tex(NAME_pos) -> texelFetch(NAME, P).
  * the Depth-to-Space pass (2x output) is written by hand below: the 2x2 sub-pixel order is mirrored
    vertically for the same reason, and MAIN is sampled bilinearly at the 2x pixel centre (as mpv does).
  * weights / biases are copied verbatim.
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'app', 'src', 'main', 'assets', 'shaders')

LICENSE_HEADER = """// =====================================================================================
// Ulfur Video 1.8.0 - {title}, GLSL ES 3.00 port (generated by tools/anime4k-port/port.py).
//
// Anime4K v4 by bloc97 - https://github.com/bloc97/Anime4K
// Copyright (c) 2019-2021 bloc97. All rights reserved.
// Licensed under the MIT License - see assets/licenses/ANIME4K_LICENSE.txt.
// Changes from the original mpv user shader: GLSL ES 3.00 instead of mpv hooks, exact texelFetch
// taps (edge-clamped) instead of MAIN_texOff, vertical offsets mirrored for GL's bottom-up texture
// orientation, one '#if PASS == n' block per mpv pass. Network weights are unchanged.
// The app prepends '#version 300 es' and '#define PASS n'.
// =====================================================================================
#ifdef GL_FRAGMENT_PRECISION_HIGH
precision highp float;
precision highp int;
#else
precision mediump float;
precision mediump int;
#endif

uniform ivec2 uSrcSize;   // source (CNN) resolution in pixels
out vec4 fragColor;
ivec2 P;                  // this fragment's texel

vec4 fetchOff(sampler2D s, vec2 o) {{
  return texelFetch(s, clamp(P + ivec2(int(o.x), -int(o.y)), ivec2(0), uSrcSize - 1), 0);
}}
vec4 fetchAt(sampler2D s) {{
  return texelFetch(s, P, 0);
}}
"""

D2S = """
#if PASS == {n}
// {desc} (hand-ported): 2x output, residual added to the bilinear 2x of MAIN.
uniform sampler2D MAIN;            // the (restored) source frame, GL_LINEAR
uniform sampler2D conv2d_last_tf;  // 4 sub-pixel residuals per source texel
void main() {{
  ivec2 po = ivec2(gl_FragCoord.xy);
  ivec2 lo = po / 2;
  ivec2 sub = po - lo * 2;
  // mpv/TensorFlow depth_to_space order is row-major from the TOP; GL rows go up, so flip the row.
  int idx = (1 - sub.y) * 2 + sub.x;
  vec4 c4 = texelFetch(conv2d_last_tf, lo, 0);
  float c = idx == 0 ? c4.x : (idx == 1 ? c4.y : (idx == 2 ? c4.z : c4.w));
  vec2 uv = (vec2(po) + 0.5) / vec2(uSrcSize * 2);
  fragColor = vec4(clamp(texture(MAIN, uv).rgb + c, 0.0, 1.0), 1.0);
}}
#endif
"""


def parse(path):
    passes = []
    cur = None
    for line in open(path):
        if line.startswith('//!DESC'):
            cur = {'desc': line[7:].strip(), 'binds': [], 'save': None, 'width': None, 'body': []}
            passes.append(cur)
        elif cur is None:
            continue
        elif line.startswith('//!BIND'):
            cur['binds'].append(line.split()[1])
        elif line.startswith('//!SAVE'):
            cur['save'] = line.split()[1]
        elif line.startswith('//!WIDTH'):
            cur['width'] = line[8:].strip()
        elif line.startswith('//!'):
            pass
        else:
            cur['body'].append(line)
    return passes


def convert(passes, title, final_clamp):
    out = [LICENSE_HEADER.format(title=title)]
    for n, p in enumerate(passes):
        if p['width'].endswith('2 *'):
            out.append(D2S.format(n=n, desc=p['desc']))
            continue
        body = ''.join(p['body'])
        body = re.sub(r'(\w+)_texOff\(', r'fetchOff(\1, ', body)
        body = re.sub(r'(\w+)_tex\(\1_pos\)', r'fetchAt(\1)', body)
        assert '_pos' not in body and '_pt' not in body and '_size' not in body, p['desc']
        last = p['save'] == 'MAIN'
        if last and final_clamp:
            body = body.replace('return result + fetchAt(MAIN);',
                                'return vec4(clamp(result.rgb + fetchAt(MAIN).rgb, 0.0, 1.0), 1.0);')
            assert 'clamp(result.rgb' in body
        out.append('\n#if PASS == %d\n// %s  ->  %s\n' % (n, p['desc'], p['save']))
        for b in p['binds']:
            out.append('uniform sampler2D %s;\n' % b)
        out.append(body.rstrip() + '\n')
        out.append('void main() {\n  P = ivec2(gl_FragCoord.xy);\n  fragColor = hook();\n}\n#endif\n')
    out.append('\n// PASS_COUNT %d\n' % len(passes))
    return ''.join(out)


def main():
    jobs = [('Anime4K_Restore_CNN_M.glsl', 'ulfur_a4k_restore_cnn_m.glsl', 'Anime4K v4.0 Restore CNN (M)', True),
            ('Anime4K_Upscale_CNN_x2_M.glsl', 'ulfur_a4k_upscale_cnn_x2_m.glsl', 'Anime4K v3.2 Upscale CNN x2 (M)', False)]
    for src, dst, title, clamp in jobs:
        passes = parse(os.path.join(HERE, 'mpv', src))
        text = convert(passes, title, clamp)
        with open(os.path.join(OUT, dst), 'w') as f:
            f.write(text)
        print(dst, len(passes), 'passes', len(text), 'bytes')


if __name__ == '__main__':
    main()
